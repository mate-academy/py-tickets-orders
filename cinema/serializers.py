from rest_framework import serializers
from django.db import transaction

from cinema.models import (
    Genre,
    Actor,
    CinemaHall,
    Movie,
    MovieSession,
    Ticket,
    Order,
)


class MovieSessionForTicketSerializer(serializers.ModelSerializer):
    movie_title = serializers.CharField(
        source="movie.title", read_only=True
    )
    cinema_hall_name = serializers.CharField(
        source="cinema_hall.name", read_only=True
    )
    cinema_hall_capacity = serializers.IntegerField(
        source="cinema_hall.capacity", read_only=True
    )

    class Meta:
        model = MovieSession
        fields = (
            "id", "show_time", "movie_title",
            "cinema_hall_name", "cinema_hall_capacity"
        )


class TicketSerializer(serializers.ModelSerializer):
    movie_session = MovieSessionForTicketSerializer(read_only=True)

    class Meta:
        model = Ticket
        fields = ("id", "row", "seat", "movie_session")


class TicketCreateSerializer(serializers.ModelSerializer):
    class Meta:
        model = Ticket
        fields = ("row", "seat", "movie_session")

    def validate(self, attrs):
        data = super().validate(attrs)
        movie_session = data["movie_session"]
        hall = movie_session.cinema_hall

        if not (1 <= data["row"] <= hall.rows):
            raise serializers.ValidationError(
                f"Row {data['row']} is out of bounds (max {hall.rows})."
            )
        if not (1 <= data["seat"] <= hall.seats_in_row):
            raise serializers.ValidationError(
                f"Seat {data['seat']} is out of bounds "
                f"(max {hall.seats_in_row})."
            )

        if Ticket.objects.filter(
            movie_session=movie_session,
            row=data["row"],
            seat=data["seat"]
        ).exists():
            raise serializers.ValidationError(
                f"Seat (row {data['row']}, seat {data['seat']}) "
                f"is already taken for this session."
            )

        return data


class OrderSerializer(serializers.ModelSerializer):
    tickets = TicketSerializer(many=True, read_only=True)

    class Meta:
        model = Order
        fields = ("id", "tickets", "created_at")


class OrderCreateSerializer(serializers.ModelSerializer):
    tickets = TicketCreateSerializer(many=True)

    class Meta:
        model = Order
        fields = ("id", "tickets", "created_at")
        read_only_fields = ("created_at",)

    def create(self, validated_data):
        tickets_data = validated_data.pop("tickets")
        with transaction.atomic():
            order = Order.objects.create(**validated_data)
            for ticket_data in tickets_data:
                Ticket.objects.create(order=order, **ticket_data)
        return order


